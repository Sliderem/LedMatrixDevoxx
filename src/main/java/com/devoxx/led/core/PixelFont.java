package com.devoxx.led.core;

import java.util.HashMap;
import java.util.Map;

/**
 * A compact 5x7 bitmap font covering A-Z, 0-9 and space, intended to stay bold
 * and legible on a 64x64 LED matrix. Each glyph is 5 columns wide and 7 rows
 * tall, stored as 7 bit-rows where bit 4 (0b10000) is the leftmost column.
 * Lowercase input is rendered using the uppercase glyphs; unknown characters
 * render as blank space.
 */
public final class PixelFont {

    public static final int GLYPH_WIDTH = 5;
    public static final int GLYPH_HEIGHT = 7;

    private static final Map<Character, int[]> GLYPHS = new HashMap<>();

    private PixelFont() {
    }

    static {
        put(' ', 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00);
        put('A', 0x0E, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11);
        put('B', 0x1E, 0x11, 0x11, 0x1E, 0x11, 0x11, 0x1E);
        put('C', 0x0E, 0x11, 0x10, 0x10, 0x10, 0x11, 0x0E);
        put('D', 0x1C, 0x12, 0x11, 0x11, 0x11, 0x12, 0x1C);
        put('E', 0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x1F);
        put('F', 0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x10);
        put('G', 0x0E, 0x11, 0x10, 0x17, 0x11, 0x11, 0x0F);
        put('H', 0x11, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11);
        put('I', 0x0E, 0x04, 0x04, 0x04, 0x04, 0x04, 0x0E);
        put('J', 0x07, 0x02, 0x02, 0x02, 0x02, 0x12, 0x0C);
        put('K', 0x11, 0x12, 0x14, 0x18, 0x14, 0x12, 0x11);
        put('L', 0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1F);
        put('M', 0x11, 0x1B, 0x15, 0x15, 0x11, 0x11, 0x11);
        put('N', 0x11, 0x19, 0x15, 0x13, 0x11, 0x11, 0x11);
        put('O', 0x0E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E);
        put('P', 0x1E, 0x11, 0x11, 0x1E, 0x10, 0x10, 0x10);
        put('Q', 0x0E, 0x11, 0x11, 0x11, 0x15, 0x12, 0x0D);
        put('R', 0x1E, 0x11, 0x11, 0x1E, 0x14, 0x12, 0x11);
        put('S', 0x0F, 0x10, 0x10, 0x0E, 0x01, 0x01, 0x1E);
        put('T', 0x1F, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04);
        put('U', 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E);
        put('V', 0x11, 0x11, 0x11, 0x11, 0x11, 0x0A, 0x04);
        put('W', 0x11, 0x11, 0x11, 0x15, 0x15, 0x1B, 0x11);
        put('X', 0x11, 0x11, 0x0A, 0x04, 0x0A, 0x11, 0x11);
        put('Y', 0x11, 0x11, 0x0A, 0x04, 0x04, 0x04, 0x04);
        put('Z', 0x1F, 0x01, 0x02, 0x04, 0x08, 0x10, 0x1F);
        put('0', 0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E);
        put('1', 0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E);
        put('2', 0x0E, 0x11, 0x01, 0x02, 0x04, 0x08, 0x1F);
        put('3', 0x1F, 0x02, 0x04, 0x02, 0x01, 0x11, 0x0E);
        put('4', 0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02);
        put('5', 0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E);
        put('6', 0x06, 0x08, 0x10, 0x1E, 0x11, 0x11, 0x0E);
        put('7', 0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08);
        put('8', 0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E);
        put('9', 0x0E, 0x11, 0x11, 0x0F, 0x01, 0x02, 0x0C);
    }

    private static void put(char c, int... rows) {
        GLYPHS.put(c, rows);
    }

    /**
     * Render {@code s} left-to-right starting at the glyph top-left (x,y).
     *
     * @param spacing extra pixel gap inserted between glyphs (0 = glyphs touch).
     */
    public static void drawText(Canvas c, String s, int x, int y, int color, int spacing) {
        int cursor = x;
        for (int i = 0; i < s.length(); i++) {
            char ch = Character.toUpperCase(s.charAt(i));
            int[] glyph = GLYPHS.get(ch);
            if (glyph != null) {
                drawGlyph(c, glyph, cursor, y, color);
            }
            cursor += GLYPH_WIDTH + spacing;
        }
    }

    /** Pixel width of a string when rendered with the given inter-glyph spacing. */
    public static int textWidth(String s, int spacing) {
        if (s.isEmpty()) {
            return 0;
        }
        return s.length() * GLYPH_WIDTH + (s.length() - 1) * spacing;
    }

    private static void drawGlyph(Canvas c, int[] glyph, int x, int y, int color) {
        for (int row = 0; row < GLYPH_HEIGHT; row++) {
            int bits = glyph[row];
            for (int col = 0; col < GLYPH_WIDTH; col++) {
                if ((bits & (1 << (GLYPH_WIDTH - 1 - col))) != 0) {
                    c.setPixel(x + col, y + row, color);
                }
            }
        }
    }
}
